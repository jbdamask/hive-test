#!/usr/bin/env python3
"""Agent roles: build the agent definitions, check them, and report whether agents ran in the right role.

The registry is hive/ROLES.json. Each role becomes .claude/agents/<name>.md, a Claude Code agent definition whose
body is the role's brief, copied from its source files. A bead for a role carries the label role:<name>;
hive/hooks/spawn_gate.py refuses a spawn whose agent type and bead label disagree.

  python3 hive/tools/roles.py build                 write .claude/agents/<name>.md for every role
  python3 hive/tools/roles.py check                 exit 1 if a definition is missing or differs from its sources
  python3 hive/tools/roles.py report [--days N]     per role for the last N days (default 7): spawned, missed
                                                    (a plain agent on a bead whose title looks like the role's
                                                    task), refused by the gate, due and ran, output written
"""
from __future__ import annotations

import argparse
import datetime as dt
import glob
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import project  # noqa: E402

ROOT = project.ROOT
REGISTRY = ROOT / "hive" / "ROLES.json"
AGENTS = ROOT / ".claude" / "agents"
SPAWN_LINE = re.compile(r"\bDo bead ([A-Za-z0-9][\w-]*(?:\.\d+)*)")


def registry() -> dict:
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def roles() -> list[dict]:
    return registry()["roles"]


def source(src: dict) -> str:
    """The text of one source: a whole file, or one `## ` section of it."""
    text = (ROOT / src["file"]).read_text(encoding="utf-8")
    if "section" not in src:
        return text.strip()
    out, keep = [], False
    for line in text.splitlines():
        if line.startswith("## "):
            keep = line[3:].strip().startswith(src["section"])
        if keep:
            out.append(line)
    if not out:
        raise ValueError(f'{src["file"]} has no section "{src["section"]}"')
    return "\n".join(out).strip()


def render(role: dict) -> str:
    named = ", ".join(s["file"] + (f' "{s["section"]}"' if "section" in s else "") for s in role["sources"])
    head = ["---",
            f"# Generated by hive/tools/roles.py from hive/ROLES.json and {named}. Edit those, then run the build.",
            f"name: {role['name']}",
            f"description: {role['does']} Team role (hive/ROLES.json); the lead spawns it"
            + (f" on a bead labelled role:{role['name']}." if role.get("needs_bead") else " with no bead."),
            "model: opus"]
    if role.get("omit_claude_md"):
        head.append("omitClaudeMd: true")
    head.append("---")
    body = [role["identity"]]
    if role.get("agent_brief"):
        body.append("You are also a one-shot agent: the agent brief added to your context at start gives your loop "
                    "and the never-do list, and it applies to you in full.")
    body.append("Your role brief follows. It is complete: you do not need to open the files it was copied from.")
    body += [source(s) for s in role["sources"]]
    return "\n".join(head) + "\n" + "\n\n".join(body) + "\n"


def build() -> int:
    AGENTS.mkdir(parents=True, exist_ok=True)
    for role in roles():
        path = AGENTS / f"{role['name']}.md"
        path.write_text(render(role), encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
    return 0


def stale() -> list[str]:
    bad = []
    for role in roles():
        path = AGENTS / f"{role['name']}.md"
        try:
            ok = path.is_file() and path.read_text(encoding="utf-8") == render(role)
        except (OSError, ValueError):
            ok = False
        if not ok:
            bad.append(role["name"])
    return bad


def check() -> int:
    bad = stale()
    if bad:
        print("out of date (run python3 hive/tools/roles.py build):", ", ".join(bad))
        return 1
    reg = registry()
    print(f"{len(reg['roles'])} agent definitions match hive/ROLES.json and their sources; "
          f"{len(reg.get('not_generated', []))} roles need none ("
          + ", ".join(r["name"] for r in reg.get("not_generated", [])) + ")")
    return 0


# ---- report ----

def _agents(since: str, projects: str):
    """(date, agent type, first prompt) for every stored subagent session on or after `since`."""
    for meta_path in glob.glob(projects + "/*/subagents/*.meta.json") + glob.glob(projects + "/*/subagents/*/*.meta.json"):
        try:
            meta = json.loads(Path(meta_path).read_text(encoding="utf-8"))
            with open(meta_path[:-len(".meta.json")] + ".jsonl", errors="replace") as f:
                first = json.loads(f.readline())
        except (OSError, ValueError):
            continue
        date = str(first.get("timestamp", ""))[:10]
        if date < since:
            continue
        content = (first.get("message") or {}).get("content")
        if isinstance(content, list):
            content = " ".join(b.get("text", "") for b in content if isinstance(b, dict))
        yield date, meta.get("agentType") or "", content or ""


def _titles() -> dict:
    r = subprocess.run(["bd", "list", "--all", "--limit", "0", "--json"], cwd=ROOT, capture_output=True, text=True,
                       timeout=120)
    try:
        return {b["id"]: b.get("title", "") for b in json.loads(r.stdout or "[]")}
    except ValueError:
        return {}


def report(days: int, projects: str | None = None, gate_log: str | None = None, titles: dict | None = None,
           today: dt.date | None = None) -> dict:
    today = today or dt.datetime.now(dt.timezone.utc).date()
    since = (today - dt.timedelta(days=days - 1)).isoformat()
    projects = projects or project.claude_projects_glob()
    gate_log = gate_log or str(project.hive_home() / "spawn_gate.jsonl")
    titles = _titles() if titles is None else titles
    out = {r["name"]: {"spawned": 0, "missed": 0, "refused": 0, "run_days": set()} for r in roles()}
    workers = 0
    for date, atype, prompt in _agents(since, projects):
        if atype in out:
            out[atype]["spawned"] += 1
            out[atype]["run_days"].add(date)
            continue
        if atype != "general-purpose":
            continue
        workers += 1
        m = SPAWN_LINE.search(prompt)
        title = titles.get(m.group(1), "") if m else ""
        for r in roles():
            if r.get("looks_like") and title and re.search(r["looks_like"], title):
                out[r["name"]]["missed"] += 1
                break
    try:
        for line in open(gate_log, errors="replace"):
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            if rec.get("decision") == "role_mismatch" and str(rec.get("ts", ""))[:10] >= since:
                for name in {rec.get("role"), rec.get("agent_type")} & set(out):
                    out[name]["refused"] += 1
    except OSError:
        pass
    for r in roles():
        o = out[r["name"]]
        ran = sorted(o.pop("run_days"))
        o["ran_days"] = len(ran)
        if r.get("every_days"):
            o["due"] = max(1, days // r["every_days"])
        if r.get("writes"):
            ok = 0
            for d in ran:
                p = ROOT / r["writes"].format(date=d)
                ok += p.is_file() and r.get("must_contain", "") in p.read_text(encoding="utf-8", errors="replace")
            o["output_ok"] = ok
    return {"from": since, "to": today.isoformat(), "days": days, "workers": workers, "roles": out}


def print_report(rep: dict) -> None:
    print(f"Roles, {rep['from']} to {rep['to']} ({rep['workers']} plain agents in the same days)")
    print(f"{'role':<22}{'spawned':>8}{'missed':>8}{'refused':>9}{'due/ran':>10}{'output':>9}")
    for name, o in rep["roles"].items():
        due = f"{o['due']}/{o['ran_days']}" if "due" in o else "-"
        outp = f"{o['output_ok']}/{o['ran_days']}" if "output_ok" in o else "-"
        print(f"{name:<22}{o['spawned']:>8}{o['missed']:>8}{o['refused']:>9}{due:>10}{outp:>9}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["build", "check", "report"])
    ap.add_argument("--days", type=int, default=7)
    a = ap.parse_args()
    if a.cmd == "build":
        return build()
    if a.cmd == "check":
        return check()
    print_report(report(a.days))
    return 0


if __name__ == "__main__":
    sys.exit(main())
