#!/usr/bin/env python3
"""Build the agent brief, .beads/PRIME.md, from hive/BRIEF.md and the project's never-do list.

`bd prime` prints .beads/PRIME.md, and the SubagentStart hook adds it to every agent at start. It is built from
the general brief (hive/BRIEF.md) with the `## Never` section of hive/PROJECT.md added before the reading table,
so each project keeps its own never-do items in its own file.

  python3 hive/tools/brief.py build     write .beads/PRIME.md
  python3 hive/tools/brief.py check     exit 1 if .beads/PRIME.md differs from a fresh build or is over the limit

The limit: Claude Code cuts a hook's added text at about 10,000 characters; the brief stays under 8,500.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERAL = ROOT / "hive" / "BRIEF.md"
PROJECT = ROOT / "hive" / "PROJECT.md"
OUT = ROOT / ".beads" / "PRIME.md"
LIMIT = 8500
TABLE = "## If your bead does X"


def never_section(text: str) -> str:
    out, keep = [], False
    for line in text.splitlines():
        if line.startswith("## "):
            keep = line[3:].strip().startswith("Never")
            if keep:
                continue
        if keep:
            out.append(line)
    return "\n".join(out).strip()


def render() -> str:
    general = GENERAL.read_text(encoding="utf-8")
    items = never_section(PROJECT.read_text(encoding="utf-8")) if PROJECT.is_file() else ""
    block = "## This project's never-do list (hive/PROJECT.md)\n" + (items or "- None yet.") + "\n\n"
    head, sep, tail = general.partition(TABLE)
    text = head + block + sep + tail if sep else general.rstrip("\n") + "\n\n" + block
    return "<!-- Generated by hive/tools/brief.py from hive/BRIEF.md and hive/PROJECT.md \"Never\". Edit those. -->\n" + text


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    text = render()
    if len(text) > LIMIT:
        print(f"the brief is {len(text)} characters; the limit is {LIMIT}. Cut a line before adding one.")
        return 1
    if cmd == "build":
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote .beads/PRIME.md ({len(text)} characters, limit {LIMIT})")
        return 0
    if cmd == "check":
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(".beads/PRIME.md is out of date: run python3 hive/tools/brief.py build")
            return 1
        print(f".beads/PRIME.md matches its sources ({len(text)} characters, limit {LIMIT})")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
